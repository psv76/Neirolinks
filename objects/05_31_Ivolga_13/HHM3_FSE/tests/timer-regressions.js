'use strict';
const assert=require('node:assert/strict'),{create}=require('./harness');
const h=create(),p='HHM3_FSE/pump_',v=k=>h.values.boiler[p+k];
h.samples();h.start();h.advance(10000);
for(const id of ['501','502','503','504','505'])assert.equal(v('start_remaining_'+id),'—');
assert.equal(v('stop_remaining_505'),'—');
h.set('boiler','NL_simple_thermostat_606/target_state',true);h.advance(5000);
assert.equal(v('start_remaining_502'),'180 с');
h.advance(175000);assert.equal(v('start_remaining_502'),'5 с');
h.advance(5000);assert.equal(v('start_remaining_502'),'—');
h.set('boiler','NL_simple_thermostat_607/target_state',true);h.advance(5000);h.advance(130000);
h.set('boiler','NL_simple_thermostat_606/target_state',false);h.advance(5000);
assert.equal(v('stop_remaining_502'),'120 с');assert.equal(v('start_remaining_502'),'—');
h.advance(40000);assert.equal(v('stop_remaining_502'),'80 с');
h.advance(5000);assert.equal(v('stop_remaining_502'),'—');
h.set('boiler','NL_simple_thermostat_607/target_state',false);h.advance(5000);
h.advance(115000);assert.equal(v('stop_remaining_502'),'5 с');
h.advance(5000);assert.equal(v('stop_remaining_502'),'—');
const events=h.messages.filter(m=>m.topic===h.C.eventTopic).map(m=>JSON.parse(m.payload)).filter(e=>/^502_(start|stop)_timer$/.test(e.circuit));
assert.equal(events.length,6,'только начало и конец трёх ожиданий, без секунд в журнале');
assert.ok(events.some(e=>e.detail==='Выбег отменён новым готовым запросом'));
h.set('boiler','NL_simple_thermostat_606/target_state',true);h.advance(5000);
h.set('boiler','NL_simple_thermostat_606/target_state',false);h.advance(5000);
assert.equal(v('start_remaining_502'),'—');
console.log('PASS таймеры 180→5→—, выбег 120→80→—, 120→5→—, отмена запроса, журнал переходов');
