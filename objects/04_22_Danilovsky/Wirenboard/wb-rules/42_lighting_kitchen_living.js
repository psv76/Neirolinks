// ============================================================================
// 2. ФИЗИЧЕСКИЕ КАНАЛЫ
// ============================================================================

var BUTTON_218_SHORT = "wb-mr6c_206/Input 4 Single Press Counter"; // Кнопка 218, короткое нажатие
var BUTTON_228_SHORT = "wb-mr6c_206/Input 1 Single Press Counter"; // Кнопка 228, короткое нажатие
var BUTTON_229_LONG = "wb-mr6c_156/Input 5 Long Press Counter";    // Кнопка 229, длинное нажатие

var LIGHT_307 = "wb-mr6c_206/K4";     // Основной свет рабочей зоны, гр.307
var LIGHT_333_3 = "wb-led_52/CCT1";   // Подсветка рабочей зоны, гр.333.3

var LIGHT_301 = "wb-mr6c_138/K1";     // Прихожая/кухня-гостиная, гр.301
var LIGHT_301_1 = "wb-mr6c_138/K2";   // Прихожая/кухня-гостиная, гр.301.1
var LIGHT_302 = "wb-mr6c_138/K3";     // Прихожая, гр.302


// ============================================================================
// 3. НАСТРОЙКИ
// ============================================================================

// Даём локальной mapping-матрице время переключить гр.307,
// после чего читаем её фактическое состояние.
var LOCAL_MAPPING_SETTLE_MS = 150;

// Защита от ложных действий сразу после запуска wb-rules.
var STARTUP_IGNORE_MS = 3000;
var SCRIPT_STARTED_AT_MS = Date.now();


// ============================================================================
// 4. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================================

function isStartupWindow() {
    return (Date.now() - SCRIPT_STARTED_AT_MS) < STARTUP_IGNORE_MS;
}

function setIfDifferent(channel, value) {
    if (dev[channel] !== value) {
        dev[channel] = value;
    }
}

// Кнопки 218 и 228 делают одно и то же.
// Основной свет 307 уже переключён самим WB-MR6C.
// Скрипт только приводит 333.3 к тому же состоянию.
function syncWorktopLight(source) {
    setTimeout(function () {
        var mainLightOn = dev[LIGHT_307] === true;

        setIfDifferent(LIGHT_333_3, mainLightOn);

        log.info("[освещение][42_lighting_kitchen_living][кухня-гостиная]; КОМАНДА=" +
            source + "; гр.307=" + (mainLightOn ? "ON" : "OFF") +
            " локально; гр.333.3=" + (mainLightOn ? "ON" : "OFF"));
    }, LOCAL_MAPPING_SETTLE_MS);
}


// ============================================================================
// 5. ПРАВИЛА
// ============================================================================

// --------------------------------------------------------------------------
// Кнопка 218, короткое.
//
// По ТЗ: вкл/выкл 333.3 + 307.
// 307 должен переключаться локально WB-MR6C206.
// Этот файл добавляет только 333.3.
// --------------------------------------------------------------------------

defineRule("kitchen_218_short_worktop", {
    whenChanged: BUTTON_218_SHORT,
    then: function () {
        if (isStartupWindow()) {
            return;
        }

        syncWorktopLight("218 short");
    }
});


// --------------------------------------------------------------------------
// Кнопка 228, короткое.
//
// По ТЗ функция совпадает с 218:
// вкл/выкл 333.3 + 307.
// 307 локальный, JS добавляет 333.3.
// --------------------------------------------------------------------------

defineRule("kitchen_228_short_worktop", {
    whenChanged: BUTTON_228_SHORT,
    then: function () {
        if (isStartupWindow()) {
            return;
        }

        syncWorktopLight("228 short");
    }
});


// --------------------------------------------------------------------------
// Кнопка 229, длинное.
//
// По ТЗ: выключить 301.1 + 301 + 302.
// Здесь нет toggle — всегда только OFF.
// --------------------------------------------------------------------------

defineRule("kitchen_229_long_entry_lights_off", {
    whenChanged: BUTTON_229_LONG,
    then: function () {
        if (isStartupWindow()) {
            return;
        }

        setIfDifferent(LIGHT_301_1, false);
        setIfDifferent(LIGHT_301, false);
        setIfDifferent(LIGHT_302, false);

        log.info("[освещение][42_lighting_kitchen_living][кухня-гостиная]; КОМАНДА=229 long; " +
            "гр.301.1=OFF; гр.301=OFF; гр.302=OFF");
    }
});


