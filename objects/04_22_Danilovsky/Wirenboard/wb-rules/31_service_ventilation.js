// ============================================================================
// Гардероб.
//
// Скрипт управляет только периодической вентиляцией гардероба:
//
// - гр.335: включать каждый час круглосуточно на 5 минут.
//
// Вентилятор кладовой гр.328 перенесён в отдельный комнатный скрипт
// 32_storage.js вместе с ручной кнопкой 207.
// ============================================================================


// ============================================================================
// 1. ФИЗИЧЕСКИЕ КАНАЛЫ
// ============================================================================

var FAN_335 = "wb-mr6c_138/K5"; // Гардероб, вентилятор гр.335


// ============================================================================
// 2. НАСТРОЙКИ
// ============================================================================

var RUN_MINUTES = 5; // Длительность одного автоматического цикла, минут


// ============================================================================
// 3. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================================

function setFan(value) {
    if (dev[FAN_335] !== value) {
        dev[FAN_335] = value;
    }
}


// ============================================================================
// 4. АВТОМАТИЧЕСКАЯ ВЕНТИЛЯЦИЯ
//
// Каждый час круглосуточно:
// - в 00 минут включить;
// - через 5 минут выключить.
// ============================================================================

defineRule("service_ventilation_335_on", {
    when: cron("0 0 * * * *"),
    then: function () {
        setFan(true);

        log.info("[вентиляция][31_service_ventilation][гардероб]; КОМАНДА=автоматическое включение; гр.335=ON");
    }
});

defineRule("service_ventilation_335_off", {
    when: cron("0 " + RUN_MINUTES + " * * * *"),
    then: function () {
        setFan(false);

        log.info("[вентиляция][31_service_ventilation][гардероб]; КОМАНДА=автоматическое выключение; гр.335=OFF");
    }
});
