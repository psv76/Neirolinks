// ============================================================================
// 1. НАЗНАЧЕНИЕ СКРИПТА
//
// Периодическая вентиляция кладовой и гардероба.
//
// Ручное управление вентиляторами уже выполнено локально в WB-модулях:
// - кнопка 207 -> wb-mr6c_218/K1, вентилятор гр.328;
// - кнопка 234 -> wb-mr6c_138/K5, вентилятор гр.335.
//
// Этот скрипт НЕ повторяет ручное управление.
// Он только добавляет автоматическое расписание из ТЗ:
//
// - гр.335: включать каждый час круглосуточно на 5 минут;
// - гр.328: включать каждый час с 09:00 до 22:00 включительно на 5 минут.
//
// При перезапуске wb-rules вне начала часа вентиляторы самопроизвольно
// не запускаются.
// ============================================================================


// ============================================================================
// 2. ФИЗИЧЕСКИЕ КАНАЛЫ
// ============================================================================

var FAN_328 = "wb-mr6c_218/K1"; // Кладовая, вентилятор гр.328
var FAN_335 = "wb-mr6c_138/K5"; // Гардероб, вентилятор гр.335


// ============================================================================
// 3. НАСТРОЙКИ
// ============================================================================

var RUN_MINUTES = 5;      // Длительность одного автоматического цикла, минут
var DAY_START_HOUR = 9;   // Первый автоматический запуск вентилятора 328
var DAY_END_HOUR = 22;    // Последний автоматический запуск вентилятора 328


// ============================================================================
// 4. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================================

// Устанавливаем состояние выхода только если оно действительно меняется.
function setFan(channel, value) {
    if (dev[channel] !== value) {
        dev[channel] = value;
    }
}


// ============================================================================
// 5. ПРАВИЛА
// ============================================================================

// --------------------------------------------------------------------------
// Гардероб, гр.335.
// Каждый час круглосуточно:
// 00 минут -> включить;
// 05 минут -> выключить.
//
// Если пользователь вручную выключил вентилятор внутри текущего 5-минутного
// цикла, скрипт не включает его повторно до следующего планового часа.
// --------------------------------------------------------------------------

defineRule("service_ventilation_335_on", {
    when: cron("0 0 * * * *"),
    then: function () {
        setFan(FAN_335, true);
    }
});

defineRule("service_ventilation_335_off", {
    when: cron("0 " + RUN_MINUTES + " * * * *"),
    then: function () {
        setFan(FAN_335, false);
    }
});


// --------------------------------------------------------------------------
// Кладовая, гр.328.
// Каждый час с 09:00 до 22:00 включительно:
// 00 минут -> включить;
// 05 минут -> выключить.
//
// Ручная кнопка 207 остаётся локальной функцией WB-MR6C218 и этим скриптом
// не обрабатывается.
// --------------------------------------------------------------------------

defineRule("service_ventilation_328_on", {
    when: cron("0 0 " + DAY_START_HOUR + "-" + DAY_END_HOUR + " * * *"),
    then: function () {
        setFan(FAN_328, true);
    }
});

defineRule("service_ventilation_328_off", {
    when: cron("0 " + RUN_MINUTES + " " + DAY_START_HOUR + "-" + DAY_END_HOUR + " * * *"),
    then: function () {
        setFan(FAN_328, false);
    }
});
