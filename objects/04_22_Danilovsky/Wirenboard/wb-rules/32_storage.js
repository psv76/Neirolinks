// ============================================================================
// Кладовая.
//
// Кнопка 208 полностью работает локально в модулях и этим скриптом
// не обрабатывается:
// - короткое нажатие: гр.315 + гр.315.1;
// - длинное нажатие: только гр.315.1.
//
// Скрипт управляет вентилятором гр.328:
// - кнопка 207: ручное включение/выключение;
// - автоматически каждый час с 09:00 до 22:00 включительно на 5 минут.
//
// Реальные каналы:
// - кнопка 207: wb-mr6c_218/Input 1;
// - вентилятор 328: wb-mr6c_218/K1.
// ============================================================================


// ============================================================================
// 1. ФИЗИЧЕСКИЕ КАНАЛЫ
// ============================================================================

var BUTTON_207 = "wb-mr6c_218/Input 1"; // Кнопка 207
var FAN_328 = "wb-mr6c_218/K1";         // Вытяжной вентилятор гр.328


// ============================================================================
// 2. НАСТРОЙКИ
// ============================================================================

var RUN_MINUTES = 5;      // Длительность автоматического включения, минут
var DAY_START_HOUR = 9;   // Первый автоматический запуск
var DAY_END_HOUR = 22;    // Последний автоматический запуск

var STARTUP_IGNORE_MS = 3000;
var SCRIPT_STARTED_AT_MS = Date.now();


// ============================================================================
// 3. ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================================

function isStartupWindow() {
    return (Date.now() - SCRIPT_STARTED_AT_MS) < STARTUP_IGNORE_MS;
}

function setFan(value) {
    if (dev[FAN_328] !== value) {
        dev[FAN_328] = value;
    }
}

function toggleFan() {
    var target = dev[FAN_328] !== true;

    setFan(target);

    log.info("[вентиляция][32_storage][кладовая]; КОМАНДА=кнопка 207; гр.328=" +
        (target ? "ON" : "OFF"));
}


// ============================================================================
// 4. РУЧНОЕ УПРАВЛЕНИЕ
//
// Вход 1 WB-MR6C218 сейчас не имеет локального действия на K1.
// Поэтому ручное управление вентилятором выполняется здесь.
//
// Реагируем только на момент нажатия (true).
// Отпускание кнопки (false) ничего не делает.
// ============================================================================

defineRule("storage_207_fan_toggle", {
    whenChanged: BUTTON_207,
    then: function (newValue) {
        if (isStartupWindow()) {
            return;
        }

        if (newValue === true) {
            toggleFan();
        }
    }
});


// ============================================================================
// 5. АВТОМАТИЧЕСКАЯ ВЕНТИЛЯЦИЯ
//
// Каждый час с 09:00 до 22:00 включительно:
// - в 00 минут включить;
// - через 5 минут выключить.
//
// Если вентилятор вручную выключили внутри текущего 5-минутного цикла,
// повторного включения до следующего часа не будет.
// ============================================================================

defineRule("storage_328_auto_on", {
    when: cron("0 0 " + DAY_START_HOUR + "-" + DAY_END_HOUR + " * * *"),
    then: function () {
        setFan(true);

        log.info("[вентиляция][32_storage][кладовая]; КОМАНДА=автоматическое включение; гр.328=ON");
    }
});

defineRule("storage_328_auto_off", {
    when: cron("0 " + RUN_MINUTES + " " + DAY_START_HOUR + "-" + DAY_END_HOUR + " * * *"),
    then: function () {
        setFan(false);

        log.info("[вентиляция][32_storage][кладовая]; КОМАНДА=автоматическое выключение; гр.328=OFF");
    }
});
